package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"

	"github.com/stubbedev/flakes.nix/internal/fetch"
	"github.com/stubbedev/flakes.nix/internal/source/gorelease"
	"github.com/stubbedev/flakes.nix/internal/update"
)

type config struct {
	Packages []packageConfig `json:"packages"`
}

type packageConfig struct {
	Name   string       `json:"name"`
	Pin    string       `json:"pin"`
	Source sourceConfig `json:"source"`
}

type sourceConfig struct {
	Type     string          `json:"type"`
	Settings json.RawMessage `json:"settings"`
}

type sourceFactory func(settings json.RawMessage, client fetch.Client) (update.Source, error)

var sources = map[string]sourceFactory{
	"go-release": func(settings json.RawMessage, client fetch.Client) (update.Source, error) {
		return gorelease.New(settings, client, gorelease.DownloadsURL)
	},
}

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	err := run(ctx, os.Args[1:], os.Stdout, os.Stderr)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, "update:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("update", flag.ContinueOnError)
	fs.SetOutput(stderr)
	configPath := fs.String("config", "", "package configuration generated by the flake")
	root := fs.String("root", ".", "repository root that pin paths are relative to")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *configPath == "" {
		return errors.New("-config is required")
	}
	if _, err := os.Stat(filepath.Join(*root, "flake.nix")); err != nil {
		return fmt.Errorf("-root %s is not the repository root: %w", *root, err)
	}

	packages, err := loadPackages(*configPath, fetch.New())
	if err != nil {
		return err
	}
	res := update.Run(ctx, *root, packages)
	for _, name := range res.Current {
		fmt.Fprintf(stderr, "%s: up to date\n", name)
	}
	for _, c := range res.Changes {
		fmt.Fprintln(stdout, c)
	}
	return res.Failures
}

func loadPackages(path string, client fetch.Client) ([]update.Package, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("load config: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg config
	if err := dec.Decode(&cfg); err != nil {
		return nil, fmt.Errorf("load config %s: %w", path, err)
	}
	packages := make([]update.Package, 0, len(cfg.Packages))
	for _, p := range cfg.Packages {
		factory, ok := sources[p.Source.Type]
		if !ok {
			return nil, fmt.Errorf("load config %s: package %s: unknown source type %q", path, p.Name, p.Source.Type)
		}
		source, err := factory(p.Source.Settings, client)
		if err != nil {
			return nil, fmt.Errorf("load config %s: package %s: %w", path, p.Name, err)
		}
		packages = append(packages, update.Package{Name: p.Name, PinPath: p.Pin, Source: source})
	}
	return packages, nil
}
